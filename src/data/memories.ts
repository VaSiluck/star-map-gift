/** Какие блоки окна звезды показывать. Отсутствующие ключи = блок показан (по умолчанию всё видно). */
export type StarBlocks = {
  /** дата / период в шапке окна */
  date?: boolean;
  /** фотография */
  photo?: boolean;
  /** подпись под фото */
  caption?: boolean;
  /** блок «Как это было» */
  story?: boolean;
  /** заголовок «Как это было» над текстом (по умолчанию показан) */
  storyLabel?: boolean;
  /** блок «Что ты мне принесла» */
  gift?: boolean;
  /** строка-цитата «Мысль вслух» */
  thought?: boolean;
  /** служебная строка внизу (latin · id · яркость) */
  meta?: boolean;
};

export type Star = {
  id: string;
  title: string;
  date: string;
  /** координаты в мировой системе неба (WORLD_W x WORLD_H) */
  x: number;
  y: number;
  /** видимая величина: 1 — яркая, 3 — тихая */
  magnitude: 1 | 2 | 3;
  photo: string;
  /** подпись под фото */
  caption: string;
  /** воспоминание — что было */
  story: string;
  /** что ты мне привнесла — ценность */
  gift: string;
  /** мысль вслух, короткая строка */
  thought: string;
  /** какие блоки окна показывать (редактируется в режиме ?edit прямо в окне) */
  blocks?: StarBlocks;
};

export type Constellation = {
  id: string;
  name: string;
  latin: string;
  subtitle: string;
  color: string;
  /** связи между звёздами: пары id */
  lines: [string, string][];
  stars: Star[];
};

export type Polaris = {
  id: string;
  title: string;
  x: number;
  y: number;
  color: string;
  heading: string;
  text: string[];
  /** показывать ли Полярную (финал карты) */
  enabled?: boolean;
};

